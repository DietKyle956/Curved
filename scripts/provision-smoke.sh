#!/usr/bin/env bash
# lsblk stub: root /dev/vda1 on disk vda (50 GiB), data /dev/vdb is vdb
# (100 GiB) and is only mounted once the mount stub has run.
set -euo pipefail

rev=0
diskonly=0
bytes=0
cols=""
target=""

args=("$@")
i=0
while [ "$i" -lt "${#args[@]}" ]; do
  arg=${args[$i]}
  case "$arg" in
    --)
      i=$((i + 1))
      while [ "$i" -lt "${#args[@]}" ]; do
        target=${args[$i]}
        i=$((i + 1))
      done
      ;;
    -o|--output)
      i=$((i + 1))
      cols=${args[$i]:-}
      ;;
    --output=*)
      cols=${arg#--output=}
      ;;
    -s|--inverse)
      rev=1
      ;;
    -*)
      case "$arg" in *s*) rev=1 ;; esac
      case "$arg" in *d*) diskonly=1 ;; esac
      case "$arg" in *b*) bytes=1 ;; esac
      ;;
    *)
      target=$arg
      ;;
  esac
  i=$((i + 1))
