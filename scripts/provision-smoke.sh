cat > "$HARNESS_DIR/bin/docker" <<'STUB'
#!/usr/bin/env bash
# docker stub: reports the data root from /etc/docker/daemon.json, refuses a
# compose up unless that root is on the data volume, models compose
# version/up (counted)/ps (healthy), answers an in-container `exec` with a
# well-formed webhook signature, and serves caddy issuance logs that match
# the public or internal environment (a marker drops the ACME issuer line).
set -euo pipefail
state=/run/smoke

daemon_data_root() {
  local root=/var/lib/docker
  local parsed=""
  if [ -f /etc/docker/daemon.json ]; then
    parsed=$(sed -n \
      's/^[[:space:]]*"data-root"[[:space:]]*:[[:space:]]*"\([^"]*\)".*$/\1/p' \
      /etc/docker/daemon.json | head -n 1) || true
    if [ -n "$parsed" ]; then
      root=$parsed
    fi
  fi
  printf '%s\n' "$root"
}

if [ "${1:-}" = info ]; then
  # The verifier negative flips the reported root to the old default.
  if [ -e "$state/docker-root-wrong" ]; then
    printf '/var/lib/docker\n'
  else
    daemon_data_root
  fi
  exit 0
fi

if [ "${1:-}" != compose ]; then
  exit 1
fi
shift
# Model the in-container HMAC helper: any exec prints a well-formed signature.
for arg in "$@"; do
  if [ "$arg" = exec ]; then
    printf 'sha256=%064d\n' 0
    exit 0
  fi
done
case "${1:-}" in
  version)
    printf 'Docker Compose version v2.29.7\n'
    exit 0
    ;;
esac
up=0
ps=0
logs=0
for arg in "$@"; do
  case "$arg" in
    up) up=1 ;;
    ps) ps=1 ;;
    logs) logs=1 ;;
  esac
done
if [ "$logs" -eq 1 ]; then
  env_file=/srv/curved/checkout/deploy/.env
  domain=""
  acme=""
  if [ -r "$env_file" ]; then
    domain=$(sed -n 's/^CURVED_DOMAIN=//p' "$env_file" | head -n 1) || true
    acme=$(sed -n 's/^ACME_EMAIL=//p' "$env_file" | head -n 1) || true
  fi
  if [ -z "$domain" ]; then
    domain=localhost
  fi
  if [ -n "$acme" ] && [ "$domain" != localhost ] &&
    [ ! -e "$state/logs-no-acme" ]; then
    printf 'certificate obtained successfully for %s (acme issuer: letsencrypt)\n' \
      "$domain"
  else
    printf 'certificate obtained successfully for %s (issuer: Caddy Local Authority)\n' \
      "$domain"
  fi
  exit 0
fi
if [ "$up" -eq 1 ]; then
  count=0
  if [ -f "$state/docker-up-count" ]; then
    count=$(cat "$state/docker-up-count")
  fi
  count=$((count + 1))
  printf '%s\n' "$count" > "$state/docker-up-count"
  printf '%s\n' "$@" > "$state/up-args-$count"
  root=$(daemon_data_root)
  if [ ! -f /etc/docker/daemon.json ] || [ "$root" != /srv/curved/docker ]; then
    : > "$state/up-without-data-root"
    printf 'docker: refusing compose up: data root is %s, expected /srv/curved/docker\n' \
      "$root" >&2
    exit 1
  fi
  printf 'stack up\n'
  exit 0
fi
if [ "$ps" -eq 1 ]; then
  printf 'db running healthy\napp running healthy\ncaddy running\n'
  exit 0
fi
exit 0
STUB

