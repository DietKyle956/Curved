#!/usr/bin/env bash
# Provisioning gate: run deploy/bootstrap-host.sh and deploy/verify-host.sh in a
# throwaway ubuntu:24.04 container, with PATH stubs standing in for the host
# tools they call. Asserts the bootstrap contract (including the docker data
# root on the data volume, migration of a pre-existing /var/lib/docker,
# daemon.json log rotation and build-cache GC, the docker.service mount
# dependency, the enabled prune timer, the hourly keepalive unit with its
# installed /usr/local/bin/curved-keepalive script, the 0700 backup directory
# with daily backup units and one initial nightly set, and the generated
# environment with and without --acme-email), the first compose up recreating
# containers so the new log defaults take effect while the idempotent re-run
# starts them without recreation, the verifier's internal and public happy
# paths (docker, backup, and keepalive checks, certificate, redirect, HSTS,
# compression, Caddy issuance, https API, and webhook), three verifier negatives
# (wrong data root, disabled prune timer, disabled keepalive timer),
# four backup verifier negatives (missing directory, stale set, corrupt
# checksum, inactive timer), six edge verifier negatives (unverified public
# certificate, missing public HSTS, HTTP 200 instead of a redirect, issuance
# log without an ACME marker, internal HSTS, unsigned webhook answering 200),
# two security boundaries (public 5432, password authentication), and two
# --acme-email argument rejections.
# The container and the temp harness are always removed; the harness is kept
# with `--keep`.
set -euo pipefail

ROOT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

IMAGE="ubuntu:24.04"
CONTAINER_NAME="curved-provision-smoke-$$"
HARNESS_DIR=""
keep=0

usage() {
  cat <<'EOF'
Usage: bash scripts/provision-smoke.sh [--keep]

Runs deploy/bootstrap-host.sh and deploy/verify-host.sh inside a throwaway
ubuntu:24.04 container. The host tools those scripts call (apt, docker, sshd,
lsblk, findmnt, blkid, blockdev, mount, mkfs.ext4, ss, curl, git, openssl,
systemctl, df) are replaced by stubs that model a 50 GiB root disk with a
100 GiB data volume, and deploy/backup.sh is replaced by a stub that publishes
a contract-shaped nightly set. The checks are: fresh bootstrap, docker data
root on the data volume, a one-time migration of the existing /var/lib/docker,
daemon.json log rotation (json-file 10m x 3) and build-cache GC (5GB), the
docker.service mount dependency, the enabled daily prune timer, the hourly
keepalive unit with /usr/local/bin/curved-keepalive installed from
deploy/keepalive.sh, the 0700 backup directory with enabled daily backup units
(03:17) and one valid initial nightly set, deploy user and key-only SSH, sshd
policy, one ext4 fstab entry, checkout, generated environment with no secret on
stdout, one compose up that recreates containers so the new log defaults apply,
an idempotent re-run that rewrites nothing, does not restart docker, and does
not recreate containers, the verifier's internal happy path (docker, backup,
and keepalive checks, certificate, redirect, absent HSTS, compression, Caddy
issuance, and HTTPS API), a wrong docker data root rejected, a disabled prune
timer rejected, a disabled keepalive timer rejected, a missing backup directory
rejected, a stale nightly set rejected, a corrupt checksum rejected, an
inactive backup timer rejected, an internal deployment sending HSTS rejected, a
public environment generated by --acme-email (CURVED_DOMAIN, ACME_EMAIL, and
CURVED_HSTS_MAX_AGE), the public verifier happy path (public certificate,
redirect, HSTS 31536000, compression, ACME issuance), public negatives for an
unverified certificate, missing HSTS, an HTTP 200 instead of a redirect, and an
issuance log without an ACME marker, a public 5432 listener rejected, password
authentication rejected, a --no-stack re-run that starts nothing, a default
localhost environment that leaves ACME_EMAIL and CURVED_HSTS_MAX_AGE empty and
verifies as the internal mode, and --acme-email rejected for localhost and
dotless hostnames.

  --keep     Keep the temp harness directory (stubs plus scenario).
  -h, --help Show this message.

The host itself is not modified; one disposable container is the only Docker
state touched.
EOF
}

while [ "$#" -gt 0 ]; do
  case "$1" in
    --keep)
      keep=1
      shift
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      printf 'provision-smoke: unknown argument %s\n\n' "$1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

fail() {
  printf 'provision-smoke: FAIL %s\n' "$1" >&2
  exit 1
}

cleanup() {
  local status=$?
  docker rm -f "$CONTAINER_NAME" >/dev/null 2>&1 || true
  if [ "$keep" -eq 0 ] && [ -n "$HARNESS_DIR" ] && [ -d "$HARNESS_DIR" ]; then
    rm -rf -- "$HARNESS_DIR"
  fi
  exit "$status"
}
trap cleanup EXIT

if ! command -v docker >/dev/null 2>&1; then
  fail "docker is required"
fi
if ! docker image inspect "$IMAGE" >/dev/null 2>&1; then
  printf 'provision-smoke: pulling %s\n' "$IMAGE"
  docker pull "$IMAGE" >/dev/null || fail "docker pull $IMAGE failed"
fi

for script in deploy/bootstrap-host.sh deploy/verify-host.sh; do
  bash -n "$script" || fail "$script does not parse"
done
printf 'PASS deploy scripts parse (bash -n)\n'

HARNESS_DIR="$(mktemp -d "${TMPDIR:-/tmp}/curved-provision-smoke.XXXXXX")"
# The harness is bind-mounted at /smoke and read by the container's git stub,
# which bootstrap-host.sh runs as the unprivileged deploy user. mktemp creates
# the directory 0700, so deploy cannot traverse it: the stub then misses
# /smoke/backup-stub.sh and installs the real deploy/backup.sh instead. Open the
# directory up and refuse to run when an ancestor stays unsearchable for
# unprivileged users, instead of losing the stub silently.
chmod 0755 "$HARNESS_DIR"
ancestor="$(dirname -- "$HARNESS_DIR")"
while :; do
  mode="$(stat -c '%a' -- "$ancestor")"
  if [ $(( ${mode: -1} % 2 )) -eq 0 ]; then
    fail "$ancestor is not searchable by other users, so the container cannot read the harness; set TMPDIR to a world-searchable path"
  fi
  [ "$ancestor" = / ] && break
  ancestor="$(dirname -- "$ancestor")"
done
mkdir -p "$HARNESS_DIR/bin"

