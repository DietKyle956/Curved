cmd=""
unit=""
prop=""
value_only=0
quiet=0
now=0
args=("$@")
i=0
while [ "$i" -lt "${#args[@]}" ]; do
  arg=${args[$i]}
  case "$arg" in
    --quiet|-q)
      quiet=1
      ;;
    --value)
      value_only=1
      ;;
    --now)
      now=1
      ;;
    -p|--property)
      i=$((i + 1))
      prop=${args[$i]:-}
      ;;
    --property=*)
      prop=${arg#--property=}
      ;;
    -*)
      ;;
    *)
      if [ -z "$cmd" ]; then
        cmd=$arg
      elif [ -z "$unit" ]; then
        unit=$arg
      fi
      ;;
  esac
  i=$((i + 1))
done

count_restart() {
  local count=0
  if [ -f "$state/restart-$1" ]; then
    count=$(cat "$state/restart-$1")
  fi
  printf '%s\n' "$((count + 1))" > "$state/restart-$1"
}

case "$cmd" in
  daemon-reload)
    exit 0
    ;;
  enable)
    [ -n "$unit" ] || exit 1
    : > "$state/enabled-$unit"
    if [ "$now" -eq 1 ]; then
      : > "$state/active-$unit"
    fi
    exit 0
    ;;
  start)
    [ -n "$unit" ] || exit 1
    : > "$state/active-$unit"
    exit 0
    ;;
  stop)
    rm -f "$state/active-$unit"
    exit 0
    ;;
  restart)
    [ -n "$unit" ] || exit 1
    : > "$state/active-$unit"
    count_restart "$unit"
    exit 0
    ;;
  is-active)
    if [ "$unit" = curved-backup.timer ] && [ -e /run/smoke/backup-timer-inactive ]; then
      if [ "$quiet" -eq 0 ]; then
        printf 'inactive\n'
      fi
      exit 1
    fi
    if [ -e "$state/active-$unit" ]; then
      if [ "$quiet" -eq 0 ]; then
        printf 'active\n'
      fi
      exit 0
    fi
    if [ "$quiet" -eq 0 ]; then
      printf 'inactive\n'
    fi
    exit 1
    ;;
  is-enabled)
    if [ "$unit" = curved-keepalive.timer ] \
      && [ -e /run/smoke/keepalive-timer-disabled ]; then
      if [ "$quiet" -eq 0 ]; then
        printf 'disabled\n'
      fi
      exit 1
    fi
    if [ "$unit" = curved-docker-prune.timer ] && [ -e /run/smoke/timer-disabled ]; then
      printf 'disabled\n'
      exit 1
    fi
    if [ -e "$state/enabled-$unit" ]; then
      if [ "$quiet" -eq 0 ]; then
        printf 'enabled\n'
      fi
      exit 0
    fi
    if [ "$quiet" -eq 0 ]; then
      printf 'disabled\n'
    fi
    exit 1
    ;;
  show)
    case "$unit" in
      docker.service)
        if [ "$prop" = RequiresMountsFor ]; then
          conf=/etc/systemd/system/docker.service.d/10-curved-data-root.conf
          mounts=""
          if [ -f "$conf" ]; then
            mounts=$(sed -n 's/^RequiresMountsFor=//p' "$conf" | head -n 1) || true
          fi
          if [ -n "$mounts" ]; then
            if [ "$value_only" -eq 1 ]; then
              printf '%s\n' "$mounts"
            else
              printf 'RequiresMountsFor=%s\n' "$mounts"
            fi
          fi
        fi
        ;;
    esac
    exit 0
    ;;
esac
exit 0
STUB

cat > "$HARNESS_DIR/bin/openssl" <<'STUB'
#!/usr/bin/env bash
# openssl stub: rand -hex N is deterministic, and the verifier's issuer probe
# (s_client ... | x509 -noout -issuer) returns a public CA for a public
# environment and Caddy's local authority otherwise.
set -euo pipefail

env_file=/srv/curved/checkout/deploy/.env
env_value() {
  local key=$1 value=
  [ -r "$env_file" ] || return 1
  value=$(sed -n "s/^$key=//p" "$env_file" | head -n 1) || true
  printf '%s' "$value"
}

case "${1:-}" in
  rand)
    shift
    n=""
    hex=0
    for arg in "$@"; do
      case "$arg" in
        -hex) hex=1 ;;
        *[!0-9]*) exit 1 ;;
        *) n=$arg ;;
      esac
    done
    if [ "$hex" -ne 1 ] || [ -z "$n" ]; then
      exit 1
    fi
    seed=$(printf 'curved-provision-smoke-%s' "$n" | sha256sum | cut -c1-64)
    printf '%s\n' "${seed:0:$((n * 2))}"
    ;;
  s_client)
    printf 'CONNECTED(00000003)\n'
    printf '%s\n' '-----BEGIN CERTIFICATE-----'
    printf '%s\n' 'stub'
    printf '%s\n' '-----END CERTIFICATE-----'
    ;;
  x509)
    # Consume the certificate stream so s_client never sees a broken pipe.
    cat >/dev/null || true
    acme=$(env_value ACME_EMAIL || true)
    domain=$(env_value CURVED_DOMAIN || true)
    if [ -n "$acme" ] && [ "$domain" != localhost ]; then
      printf "issuer=C = US, O = Let's Encrypt, CN = R11\n"
    else
      printf 'issuer=CN = Caddy Local Authority - ECC Intermediate\n'
    fi
    ;;
  *)
    exit 1
    ;;
esac
exit 0
STUB

